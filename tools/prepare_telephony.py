"""Extract hash-pinned LP3 IMS components from verified stock partition images."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile

from prepare_firmware import verify

from paths import SOURCE as ROOT
PROFILE = ROOT / 'device/light/LightPhoneIII/configs/telephony-1440.json'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def native_module(filename):
    return 'lp3_ims_' + re.sub(r'[^a-zA-Z0-9_]', '_', filename.removesuffix('.so'))


def blueprint(profile):
    lines = ['// Generated by tools/prepare_telephony.py from verified LP3 firmware.', '']
    for name, app in profile['apps'].items():
        lines += ['android_app_import {', f'    name: "{name}",',
                  f'    apk: "proprietary/{app["path"]}",', '    certificate: "platform",',
                  '    system_ext_specific: true,']
        if app['privileged']:
            lines.append('    privileged: true,')
        lines += ['    uses_libs: ' + json.dumps(app['uses_libs']) + ',', '}', '']
    for name, info in profile['native_needed'].items():
        dependencies = [native_module(n) if n in profile['native_needed'] else n.removesuffix('.so')
                        for n in info['needed'] if n not in ['libc.so', 'libm.so', 'libdl.so']]
        lines += ['cc_prebuilt_library_shared {', f'    name: "{native_module(name)}",',
                  f'    stem: "{name.removesuffix(".so")}",',
                  f'    srcs: ["proprietary/system_ext/lib64/{name}"],',
                  '    compile_multilib: "64",', '    system_ext_specific: true,',
                  '    strip: { none: true },',
                  '    shared_libs: ' + json.dumps(dependencies) + ',', '}', '']
    return '\n'.join(lines) + '\n'


def product_make(profile):
    modules = list(profile['apps']) + list(profile['java_libraries'])
    modules += [native_module(n) for n in profile['native_needed']]
    modules += ['ims_ext_common.xml', 'qti_telephony_hidl_wrapper.xml', 'qti_telephony_utils.xml', 'QtiTelephonyCompat']
    text = "# Generated LP3 IMS and telephony components.\n" + "".join("PRODUCT_PACKAGES += " + module + "\n" for module in modules)
    for path in profile['files']:
        if path == 'system_ext/etc/permissions/qti_permissions.xml':
            partition, relative = path.split('/', 1)
            text += ('PRODUCT_COPY_FILES += vendor/light/LightPhoneIII/telephony/proprietary/'
                     + path + ':$(TARGET_COPY_OUT_' + partition.upper() + ')/' + relative + '\n')
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--images', type=Path, default=ROOT / 'firmware/images')
    parser.add_argument('--output', type=Path, default=ROOT / 'vendor/light/LightPhoneIII/telephony')
    args = parser.parse_args()
    profile = json.loads(PROFILE.read_text())
    firmware = json.loads((ROOT / 'device/light/LightPhoneIII/configs/firmware-1440.json').read_text())
    if profile['firmware'] != firmware['firmware']:
        raise ValueError('Telephony firmware profile mismatch')
    bp, mk = blueprint(profile), product_make(profile)
    # A prepared tree is reusable only while every file remains unchanged.
    marker = args.output / 'preparation.json'
    if marker.is_file():
        prepared = json.loads(marker.read_text())
        if prepared.get('profile_sha256') == digest(PROFILE):
            if not all((args.output / p).is_file() and digest(args.output / p) == sha
                       for p, sha in prepared['files'].items()):
                raise ValueError('Prepared telephony files changed; preserving them')
            if (args.output / 'Android.bp').read_text() == bp and (args.output / 'telephony-vendor.mk').read_text() == mk:
                print('Verified LP3 telephony inputs already prepared')
                return
    if args.output.exists():
        raise ValueError('Unmanaged or outdated telephony output; choose a fresh directory')
    partitions = sorted({name.split('/', 1)[0] for name in profile['files']})
    for partition in partitions:
        verify(args.images / (partition + '_b.img'), firmware['partitions'][partition])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.lp3-ims-', dir=args.output.parent) as temporary:
        stage = Path(temporary) / 'tree'
        for path, expected in profile['files'].items():
            partition, relative = path.split('/', 1)
            target = stage / 'proprietary' / path
            target.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(['debugfs', '-R', f'dump /{relative} {target}',
                            str(args.images / (partition + '_b.img'))],
                           check=True, capture_output=True)
            if not target.is_file() or digest(target) != expected:
                raise ValueError('Stock telephony input hash mismatch: ' + path)
        (stage / 'Android.bp').write_text(bp)
        (stage / 'telephony-vendor.mk').write_text(mk)
        files = {str(p.relative_to(stage)): digest(p) for p in stage.rglob('*') if p.is_file()}
        (stage / 'preparation.json').write_text(json.dumps({
            'firmware': profile['firmware'], 'profile_sha256': digest(PROFILE),
            'source_partition_hashes_verified': True, 'source_files_verified': len(profile['files']),
            'java_libraries_built_from_source': list(profile['java_libraries']),
            'files': files}, indent=2) + '\n')
        stage.rename(args.output)
    print(f'Prepared {len(profile["files"])} verified LP3 IMS/telephony inputs')


if __name__ == '__main__':
    main()
